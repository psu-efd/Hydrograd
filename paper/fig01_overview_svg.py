"""Figure 1 of the Hydrograd v2.0 paper as an editable Inkscape SVG (Times New Roman).

Layout (mm, 170 x 94): four columns read left to right. Inputs and parameters feed the
discrete model (residual R(U; theta) on the unstructured mesh); the model is solved by one
of three solvers, each with its matching gradient method; the gradients return along the
bottom to the loss and optimiser, which update the parameters.

The file paper/figures/fig01_overview.svg was generated by this script and then edited by
hand in Inkscape (2026-11-05); it is the master copy of the figure. Rerunning this script
would discard those edits, so write to another file name and merge by hand if needed.

Usage:
    python fig01_overview_svg.py OUT.svg
"""

import pathlib
import random
import sys

# Page size [mm].
W, H = 170.0, 94.0

# Style shared with the author's proposal figures: light grey boxes, thin black strokes,
# Times New Roman, upright labels.
BOX = "fill:#000000;fill-opacity:0.08;stroke:#000000;stroke-width:0.4"
BOX_LOOP = "fill:#000000;fill-opacity:0.03;stroke:#000000;stroke-width:0.4;stroke-dasharray:1.2,0.8"
LINE = "fill:none;stroke:#000000;stroke-width:0.4;marker-end:url(#head)"
LINE_LOOP = "fill:none;stroke:#000000;stroke-width:0.4;stroke-dasharray:1.2,0.8;marker-end:url(#head)"
FONT = "font-family:'Times New Roman';-inkscape-font-specification:'Times New Roman';fill:#000000"
TITLE = f"font-size:3.0px;font-weight:bold;{FONT}"
HEAD = f"font-size:3.2px;font-weight:bold;text-anchor:middle;{FONT}"
BODY = f"font-size:2.45px;{FONT}"
SMALL = f"font-size:2.3px;font-style:italic;{FONT}"

parts = []


def text(x, y, s, style, anchor=None):
    """Add one text line; s may contain <tspan> markup (italics, subscripts)."""
    a = f";text-anchor:{anchor}" if anchor else ""
    parts.append(f'<text x="{x:.2f}" y="{y:.2f}" style="{style}{a}" xml:space="preserve">{s}</text>')


def it(s):
    """Italic span (math symbols)."""
    return f'<tspan style="font-style:italic">{s}</tspan>'


def bf(s):
    """Bold span (vectors)."""
    return f'<tspan style="font-weight:bold">{s}</tspan>'


def sub(s):
    """Subscript span."""
    return f'<tspan style="font-size:70%;baseline-shift:sub">{s}</tspan>'


def sup(s):
    """Superscript span."""
    return f'<tspan style="font-size:70%;baseline-shift:super">{s}</tspan>'


def box(label, x, y, w, h, title, lines, style=BOX, lead=3.1):
    """A grouped rounded box with a bold title and body lines."""
    parts.append(f'<g inkscape:label="{label}">')
    parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1.2" ry="1.2" style="{style}"/>')
    text(x + 1.6, y + 3.6, title, TITLE)
    for i, ln in enumerate(lines):
        text(x + 1.6, y + 7.0 + i * lead, ln, BODY)
    parts.append("</g>")


def arrow(label, pts, style=LINE):
    """Polyline arrow through pts [(x, y), ...]."""
    d = "M " + " L ".join(f"{x:.2f},{y:.2f}" for x, y in pts)
    parts.append(f'<path inkscape:label="{label}" d="{d}" style="{style}"/>')


def mesh_sketch(x0, y0, w, h):
    """Small unstructured mesh: quadrilaterals on the left, triangles on the right."""
    rng = random.Random(3)
    nx, ny = 6, 4
    X = [[x0 + w * j / (nx - 1) for j in range(nx)] for _ in range(ny)]
    Y = [[y0 + h * i / (ny - 1) for j in range(nx)] for i in range(ny)]
    for i in range(1, ny - 1):
        for j in range(1, nx - 1):
            X[i][j] += rng.uniform(-0.9, 0.9)
            Y[i][j] += rng.uniform(-0.7, 0.7)
    parts.append('<g inkscape:label="mesh sketch">')
    sty = "fill:#ffffff;stroke:#000000;stroke-width:0.25;stroke-linejoin:round"
    for i in range(ny - 1):
        for j in range(nx - 1):
            c = [(X[i][j], Y[i][j]), (X[i][j + 1], Y[i][j + 1]),
                 (X[i + 1][j + 1], Y[i + 1][j + 1]), (X[i + 1][j], Y[i + 1][j])]
            cells = [c] if j < 3 else [[c[0], c[1], c[2]], [c[0], c[2], c[3]]]
            for cell in cells:
                d = "M " + " L ".join(f"{x:.2f},{y:.2f}" for x, y in cell) + " Z"
                parts.append(f'<path d="{d}" style="{sty}"/>')
    parts.append("</g>")


# ---------------------------------------------------------------- geometry (mm)
X_IN, W_IN = 2.0, 34.5          # inputs and parameters column
X_MD, W_MD = 41.5, 39.0         # model column
X_SV, W_SV = 85.5, 36.0         # solver column
X_GR, W_GR = 126.5, 38.0        # gradient column
X_COLLECT = 167.0               # vertical collector line of the gradients
Y_TOP = 7.0
ROWS = [(7.0, 19.0), (28.0, 19.0), (49.0, 19.0)]   # (y, h) of the three solver rows
Y_BOT, H_BOT = 74.0, 16.0       # bottom band: loss and optimiser

# ---------------------------------------------------------------- column headers
for xc, s in [(X_IN + W_IN / 2, "Inputs and parameters"), (X_MD + W_MD / 2, "Discrete model"),
              (X_SV + W_SV / 2, "Solver"), (X_GR + W_GR / 2, "Gradient of the loss")]:
    text(xc, 4.2, s, HEAD)

# ---------------------------------------------------------------- left column
box("inputs", X_IN, Y_TOP, W_IN, 29.0, "Inputs", [
    "SRH-2D unstructured mesh:",
    "triangles, quadrilaterals,",
    "polygons",
    "materials: roughness zones",
    "boundary conditions:",
    f"{it('Q')}({it('t')}), WSE({it('t')}) series",
    "run control (JSON)",
])
theta = it("θ")
box("parameters", X_IN, 40.0, W_IN, Y_BOT + H_BOT - 40.0, f"Parameters {bf(theta)}", [
    f"Manning's {it('n')} (zones, laws)",
    f"NN closure weights {bf(it('w'))}",
    f"bed elevation {it('z')}{sub(it('b'))}, inflow {it('Q')}({it('t')})",
    f"vegetation drag {it('C')}{sub(it('D'))}",
    "turbulence, wall friction and",
    f"dispersion ({it('C')}{sub(it('t'))}, {it('C')}{sub(it('m'))}, {it('k')}{sub(it('s,w'))}, {it('β')})",
])

# ---------------------------------------------------------------- model column
R = bf(it("R")); U = bf(it("U")); J = bf(it("J"))
box("model", X_MD, Y_TOP, W_MD, ROWS[-1][0] + ROWS[-1][1] - Y_TOP,
    f"Residual {R}({U}; {bf(theta)})", [
    "finite volumes on the mesh",
    "hydrostatic reconstruction, HLLC",
    "1st or 2nd order, wetting and drying",
    "closures: friction, NN, vegetation,",
    "turbulence",
    f"exact sparse Jacobian {J} = ∂{R}/∂{U}",
    "(graph colouring)",
])
mesh_sketch(X_MD + 5.0, Y_TOP + 36.0, W_MD - 10.0, 12.0)

box("loss", X_MD, Y_BOT, W_MD, H_BOT, f"Loss {it('L')} and optimiser", [
    "loss on WSE, velocities, forces",
    f"Adam, L-BFGS update {bf(theta)}:",
    "calibration and closure learning",
], style=BOX_LOOP)

# ---------------------------------------------------------------- solver and gradient rows
lam = bf(it("λ"))
solvers = [
    ("Steady flow", [
        f"Newton iteration {R}({U}*; {bf(theta)}) = {bf('0')}",
        "pseudo-transient continuation",
        "exact sparse Jacobian",
    ]),
    ("Unsteady flow, explicit", [
        "SSP-RK3, CFL time steps",
        "point-implicit friction",
        "wet–dry fronts",
    ]),
    ("Unsteady flow, implicit", [
        "backward Euler, Crank–Nicolson",
        "Newton solve per time step",
        "large time steps",
    ]),
]
gradients = [
    ("Implicit function theorem", [
        f"{J}{sup('T')}{lam} = ∂{it('L')}/∂{U}",
        "one linear solve, independent",
        "of the number of parameters",
    ]),
    ("Reverse-mode AD", [
        "checkpointing (fixed memory)",
        "≈ 4–8 forward runs",
    ]),
    ("Adjoint per time step", [
        "one linear solve per step",
        "≈ 2–2.6 forward runs",
    ]),
]
for (y, h), (st, sl), (gt, gl) in zip(ROWS, solvers, gradients):
    box(f"solver: {st}", X_SV, y, W_SV, h, st, sl)
    box(f"gradient: {gt}", X_GR, y, W_GR, h, gt, gl)
    yc = y + h / 2
    arrow("model to solver", [(X_MD + W_MD, yc), (X_SV, yc)])
    arrow("solver to gradient", [(X_SV + W_SV, yc), (X_GR, yc)])
    # Gradient output joins the collector line (no arrow head on the stub).
    parts.append(f'<path d="M {X_GR + W_GR},{yc:.2f} L {X_COLLECT},{yc:.2f}" '
                 f'style="fill:none;stroke:#000000;stroke-width:0.4;stroke-dasharray:1.2,0.8"/>')

# ---------------------------------------------------------------- arrows of the loop
y_loop = Y_BOT + H_BOT / 2
arrow("inputs to model", [(X_IN + W_IN, Y_TOP + 13.5), (X_MD, Y_TOP + 13.5)])
arrow("parameters to model", [(X_IN + W_IN, 46.0), (X_MD, 46.0)])
# Collector: from the first row down to the loop row, then left into the loss box.
arrow("gradients to loss", [(X_COLLECT, ROWS[0][0] + ROWS[0][1] / 2), (X_COLLECT, y_loop),
                            (X_MD + W_MD, y_loop)], style=LINE_LOOP)
text((X_MD + W_MD + X_COLLECT) / 2, y_loop - 1.2,
     f"d{it('L')}/d{bf(theta)}", BODY, anchor="middle")
# Optimiser updates the parameters.
arrow("update", [(X_MD, y_loop), (X_IN + W_IN, y_loop)], style=LINE_LOOP)
# State U passes from the solver to the gradient: small labels on the first row only.
text(X_SV + W_SV + 2.5, ROWS[0][0] + ROWS[0][1] / 2 - 1.2, bf(it("U")), BODY, anchor="middle")

# ---------------------------------------------------------------- write the file
svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
     width="{W}mm" height="{H}mm" viewBox="0 0 {W} {H}" version="1.1">
<defs>
<marker id="head" orient="auto" refX="2.6" refY="0" markerWidth="4" markerHeight="4"
        markerUnits="strokeWidth" style="overflow:visible">
<path d="M -0.4,0 L -3.0,-1.3 L -2.2,0 L -3.0,1.3 Z" style="fill:#000000;stroke:none"/>
</marker>
</defs>
<rect x="0" y="0" width="{W}" height="{H}" style="fill:#ffffff;stroke:none"/>
{chr(10).join(parts)}
</svg>
'''
pathlib.Path(sys.argv[1]).write_text(svg, encoding="utf-8")
print("wrote", sys.argv[1])
